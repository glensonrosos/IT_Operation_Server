import cors from 'cors';
import cookieParser from 'cookie-parser';
import express from 'express';
import rateLimit from 'express-rate-limit';
import helmet from 'helmet';
import pinoHttp from 'pino-http';
import { randomUUID } from 'node:crypto';
import { env } from './config/env.js';
import { isAllowedOrigin } from './config/origins.js';
import { errorHandler, notFoundHandler } from './middleware/errorHandler.js';
import authRoutes from './routes/authRoutes.js';
import healthRoutes from './routes/healthRoutes.js';
import roleRoutes from './routes/roleRoutes.js';
import userRoutes from './routes/userRoutes.js';
import permissionRoutes from './routes/permissionRoutes.js';
import employeeRoutes from './routes/employeeRoutes.js';
import departmentRoutes from './routes/departmentRoutes.js';
import { csrfProtection } from './middleware/csrfProtection.js';
import { logger } from './utils/logger.js';
import ticketRoutes from './routes/ticketRoutes.js';
import ticketCategoryRoutes from './routes/ticketCategoryRoutes.js';
import slaRoutes from './routes/slaRoutes.js';
import assetRoutes from './routes/assetRoutes.js';
import assetTypeRoutes from './routes/assetTypeRoutes.js';
import assetTransferRoutes from './routes/assetTransferRoutes.js';
import assetReturnRoutes from './routes/assetReturnRoutes.js';
import borrowingRoutes from './routes/borrowingRoutes.js';
import knowledgeRoutes from './routes/knowledgeRoutes.js';
import sparePartRoutes from './routes/sparePartRoutes.js';
import sparePartTypeRoutes from './routes/sparePartTypeRoutes.js';
import settingsRoutes from './routes/settingsRoutes.js';
import maintenanceRoutes from './routes/maintenanceRoutes.js';
import maintenanceScheduleRoutes from './routes/maintenanceScheduleRoutes.js';
import warrantyRoutes from './routes/warrantyRoutes.js';
import reportRoutes from './routes/reportRoutes.js';
import auditRoutes from './routes/auditRoutes.js';
import { auditLogging } from './middleware/auditLogging.js';

const app = express();

app.disable('x-powered-by');
if (env.TRUST_PROXY !== 'false') app.set('trust proxy', env.TRUST_PROXY);
app.use(pinoHttp({ logger, genReqId: () => randomUUID() }));
app.use(helmet());
app.use(cors({ origin: (origin, callback) => callback(null, isAllowedOrigin(origin) ? origin ?? env.CLIENT_URL : false), credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: false, limit: '1mb' }));
app.use(cookieParser());
app.use('/api', csrfProtection);
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.use('/api', auditLogging);
app.use('/api/health', healthRoutes);
app.use('/api/auth', authRoutes);
app.use('/api/users', userRoutes);
app.use('/api/roles', roleRoutes);
app.use('/api/permissions', permissionRoutes);
app.use('/api/employees', employeeRoutes);
app.use('/api/departments', departmentRoutes);
app.use('/api/tickets', ticketRoutes);
app.use('/api/ticket-categories', ticketCategoryRoutes);
app.use('/api/sla-policies', slaRoutes);
app.use('/api/assets', assetRoutes);
app.use('/api/asset-types', assetTypeRoutes);
app.use('/api/asset-transfers', assetTransferRoutes);
app.use('/api/asset-returns', assetReturnRoutes);
app.use('/api/borrowings', borrowingRoutes);
app.use('/api/knowledge', knowledgeRoutes);
app.use('/api/spare-parts', sparePartRoutes);
app.use('/api/spare-part-types', sparePartTypeRoutes);
app.use('/api/settings', settingsRoutes);
app.use('/api/maintenance', maintenanceRoutes);
app.use('/api/maintenance-schedules', maintenanceScheduleRoutes);
app.use('/api/warranties', warrantyRoutes);
app.use('/api/reports', reportRoutes);
app.use('/api/audit-logs', auditRoutes);
app.use(notFoundHandler);
app.use(errorHandler);

export default app;
